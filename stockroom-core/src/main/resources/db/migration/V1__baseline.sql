create table skus (
    id              bigint generated by default as identity primary key,
    code            varchar(40)  not null,
    name            varchar(120) not null,
    description     varchar(500),
    unit_of_measure varchar(10)  not null,
    reorder_point   integer      not null default 0,
    active          boolean      not null default true,
    created_at      timestamp    not null,
    constraint uk_skus_code unique (code)
);

create table locations (
    id         bigint generated by default as identity primary key,
    code       varchar(20)  not null,
    name       varchar(120) not null,
    constraint uk_locations_code unique (code)
);

create table bins (
    id          bigint generated by default as identity primary key,
    location_id bigint      not null references locations (id),
    code        varchar(20) not null,
    aisle       varchar(4)  not null,
    bay         integer     not null,
    pickable    boolean     not null default true,
    constraint uk_bins_location_code unique (location_id, code)
);

create table stock_levels (
    id        bigint generated by default as identity primary key,
    sku_id    bigint  not null references skus (id),
    bin_id    bigint  not null references bins (id),
    on_hand   integer not null default 0,
    reserved  integer not null default 0,
    constraint uk_stock_levels_sku_bin unique (sku_id, bin_id),
    constraint ck_stock_levels_on_hand check (on_hand >= 0)
);

create table stock_movements (
    id          bigint generated by default as identity primary key,
    sku_id      bigint      not null references skus (id),
    bin_id      bigint      not null references bins (id),
    type        varchar(20) not null,
    quantity    integer     not null,
    reference   varchar(60),
    transfer_id varchar(36),
    occurred_at timestamp   not null
);

create index ix_stock_movements_occurred_at on stock_movements (occurred_at);

create table reservations (
    id          bigint generated by default as identity primary key,
    reference   varchar(40) not null,
    order_ref   varchar(60) not null,
    sku_id      bigint      not null references skus (id),
    bin_id      bigint      not null references bins (id),
    quantity    integer     not null,
    status      varchar(20) not null,
    created_at  timestamp   not null,
    expires_at  timestamp   not null,
    constraint uk_reservations_reference unique (reference)
);

create table low_stock_alerts (
    id            bigint generated by default as identity primary key,
    sku_id        bigint    not null references skus (id),
    available     integer   not null,
    reorder_point integer   not null,
    raised_at     timestamp not null,
    acknowledged  boolean   not null default false
);
